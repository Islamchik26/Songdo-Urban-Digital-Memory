def q(value: object) -> str:
    """SQL literal."""
    if value is None or value == "":
        return "NULL"
    if isinstance(value, (int, float)):
        return repr(value)
    return "'" + str(value).replace("'", "''") + "'"


def core_section() -> list[str]:
    lines = ["-- ---- core.source_registry (from source_registry.csv) ----"]
    with (ROOT / "source_registry.csv").open(encoding="utf-8", newline="") as fh:
        for r in csv.DictReader(fh):
            lines.append(
                "INSERT INTO core.source_registry (source_id, title_ko, title_en, provider, source_url, "
                "verification_level, provenance, fallback_strategy, notes) VALUES ("
                + ", ".join([q(r["source_id"]), q(r["title_ko"]), q(r["title_en"]), q(r["provider"]),
                             q(r["source_url"]), str(int(r["verification_level"])), q(r["provenance"]),
                             q(r["fallback_strategy"]), q(r["notes"])])
                + ") ON CONFLICT (source_id) DO UPDATE SET title_ko = EXCLUDED.title_ko, "
                  "title_en = EXCLUDED.title_en, provider = EXCLUDED.provider, source_url = EXCLUDED.source_url, "
                  "verification_level = EXCLUDED.verification_level, provenance = EXCLUDED.provenance, "
                  "fallback_strategy = EXCLUDED.fallback_strategy, notes = EXCLUDED.notes;"
            )
    lines += ["", "-- ---- core.places (curated landmarks) ----"]
    for pid, ko, en, cat, addr, lon, lat in PLACES:
        lines.append(
            "INSERT INTO core.places (place_id, name_ko, name_en, category, road_address, geom, provenance) VALUES ("
            f"{q(pid)}, {q(ko)}, {q(en)}, {q(cat)}, {q(addr)}, "
            f"ST_SetSRID(ST_MakePoint({lon:.6f}, {lat:.6f}), 4326), 'SRC_CORE_01') "
            "ON CONFLICT (place_id) DO UPDATE SET name_ko = EXCLUDED.name_ko, name_en = EXCLUDED.name_en, "
            "category = EXCLUDED.category, road_address = EXCLUDED.road_address, geom = EXCLUDED.geom;"
        )
    return lines


